-- 사용자 행동 로그 (docs/board-schema.md 13장).
--
-- 있었던 일을 쌓기만 하고 지우거나 고치지 않는다. 좋아요 취소처럼 앞의 기록을 무르는 행동도 새 행으로 쌓고,
-- 무엇을 지우고 합칠지는 로그를 읽는 후처리가 정한다.
--
-- 외래 키를 걸지 않는다. 좋아요가 0이 된 보드는 완전 삭제되고(11-6) 사용자는 탈퇴할 수 있는데, 로그는 그때의 기록이라
-- 보드·사용자가 없어져도 남아야 한다. 같은 이유로 payload에 보드 id만 두지 않고 그 순간의 제목·아이템을 복사한다.
--
-- 좋아요·보드 저장과 같은 트랜잭션에서 넣는다. 그 요청이 이미 잡은 커넥션을 쓰므로 커넥션을 더 차지하지 않고,
-- 롤백되면 로그도 함께 빠진다(13-1).
--
-- created_at은 DB의 now(), 곧 트랜잭션 시작 시각이다. 한 행동이 이벤트 두 개를 만들면(좋아요한 내 보드 삭제 →
-- BOARD_UNLIKE + BOARD_DELETE) 두 행의 시각이 정확히 같아, 후처리가 (user_id, boardId, created_at)으로 짝을 찾는다(13-3).
--
-- 인덱스는 기본 키뿐이다. 읽는 쪽(AI 개발자의 내보내기, 백엔드 기능)의 조회 모양이 아직 정해지지 않았고,
-- 인덱스마다 행동 한 번의 쓰기가 늘어난다. 기간으로 내보낼 때는 id가 시간 순이라 id 범위로 끊어 읽을 수 있다.
-- 읽는 모양이 정해지면 그때 근거를 재서 넣는다.

create table user_event_log (
    id         bigint generated by default as identity,
    user_id    bigint                      not null,
    event_type varchar(32)                 not null
        check (event_type in ('BOARD_LIKE','BOARD_UNLIKE','BOARD_DELETE','BOARD_EDIT','BOARD_CAPTURE')),
    payload    jsonb                       not null,
    created_at timestamp(6) with time zone not null default now(),
    primary key (id)
);
